# Generates BlaiseReportsFonts.pas: subset DejaVu Sans (Latin + Greek) for the PDF exporter.
# Needs fonttools and the TTF files of dejavu-fonts-ttf-2.37:
#   https://github.com/dejavu-fonts/dejavu-fonts/releases/tag/version_2_37
# Usage: python make_pdf_fonts.py <ttf dir> <output .pas>
# Copy the output next to all three copies of BlaiseReports.pas.
import base64, io, os, sys, zlib
from fontTools import subset
from fontTools.ttLib import TTFont

ttf_dir, out_path = sys.argv[1], sys.argv[2]

WINANSI_EXTRA = [0x0152, 0x0153, 0x0160, 0x0161, 0x0178, 0x017D, 0x017E, 0x0192, 0x02C6, 0x02DC,
                 0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2020, 0x2021,
                 0x2022, 0x2026, 0x2030, 0x2039, 0x203A, 0x20AC, 0x2122]
WANTED = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + WINANSI_EXTRA + list(range(0x0370, 0x0400))


def build(file_name):
    opts = subset.Options()
    opts.hinting = False
    opts.layout_features = []
    opts.name_IDs = [1, 2, 4, 6]
    opts.notdef_outline = True
    opts.glyph_names = False
    font = TTFont(os.path.join(ttf_dir, file_name))
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=WANTED)
    sub.subset(font)
    for tag in ('GSUB', 'GPOS', 'GDEF', 'kern', 'FFTM', 'gasp'):
        if tag in font:
            del font[tag]
    buf = io.BytesIO()
    font.save(buf)
    raw = buf.getvalue()

    font = TTFont(io.BytesIO(raw))
    order = font.getGlyphOrder()
    scale = 1000.0 / font['head'].unitsPerEm
    cmap = font.getBestCmap()
    gid_of = {name: i for i, name in enumerate(order)}
    pairs = sorted((u, gid_of[g]) for u, g in cmap.items())
    widths = [round(font['hmtx'][g][0] * scale) for g in order]
    head, os2 = font['head'], font['OS/2']
    a85 = base64.a85encode(zlib.compress(raw, 9)).decode('ascii') + '~>'
    return dict(
        name=font['name'].getDebugName(6),
        length1=len(raw),
        data=a85,
        pairs=pairs,
        widths=widths,
        bbox=[round(v * scale) for v in (head.xMin, head.yMin, head.xMax, head.yMax)],
        ascent=round(font['hhea'].ascent * scale),
        descent=round(font['hhea'].descent * scale),
        cap=round(os2.sCapHeight * scale) if getattr(os2, 'sCapHeight', 0) else 729,
    )


def pas_string(name, value, indent='  '):
    chunks = [value[i:i + 100] for i in range(0, len(value), 100)] or ['']
    body = (' +\n' + indent + '  ').join("'" + c.replace("'", "''") + "'" for c in chunks)
    return indent + name + ' =\n' + indent + '  ' + body + ';\n'


regular, bold = build('DejaVuSans.ttf'), build('DejaVuSans-Bold.ttf')
out = []
out.append('unit BlaiseReportsFonts;\n\n')
out.append('{ GENERATED by packages/blaise-reports/tools/make_pdf_fonts.py, do not edit by hand.\n')
out.append('  Subset (Latin + Greek, no hinting) of DejaVu Sans 2.37 for the BlaiseReports PDF exporter.\n')
out.append('  Font licence: see DEJAVU-LICENSE next to this unit.\n')
out.append('  Each font is a zlib-compressed TrueType file in ASCII85, so a PDF stays pure ASCII. }\n\n')
out.append('{$mode objfpc}\n\ninterface\n\nconst\n')
for key, f in (('Regular', regular), ('Bold', bold)):
    out.append(pas_string('BVPdfFont%sName' % key, f['name']))
    out.append('  BVPdfFont%sLength1 = %d;\n' % (key, f['length1']))
    out.append("  BVPdfFont%sBBox = '%s';\n" % (key, ' '.join(map(str, f['bbox']))))
    out.append('  BVPdfFont%sAscent = %d;\n' % (key, f['ascent']))
    out.append('  BVPdfFont%sDescent = %d;\n' % (key, f['descent']))
    out.append('  BVPdfFont%sCapHeight = %d;\n' % (key, f['cap']))
    # unicode:gid pairs in hex, then the width of every gid in order
    out.append(pas_string('BVPdfFont%sCmap' % key, ','.join('%x:%x' % p for p in f['pairs'])))
    out.append(pas_string('BVPdfFont%sWidths' % key, ' '.join(map(str, f['widths']))))
    out.append(pas_string('BVPdfFont%sData' % key, f['data']))
out.append('\nimplementation\n\nend.\n')
with open(out_path, 'w', encoding='ascii', newline='\r\n') as fh:
    fh.write(''.join(out).replace('\r\n', '\n'))

for key, f in (('regular', regular), ('bold', bold)):
    print(key, f['name'], 'glyphs', len(f['widths']), 'ttf', f['length1'], 'a85', len(f['data']), 'bbox', f['bbox'], 'cap', f['cap'])
print('unit size', os.path.getsize(out_path))
